// Bundles the runtime agent (packages/deploy/src/agent/main.ts) into ONE self-contained file: packages/deploy/agent/pso-agent.mjs.
// The agent runs on the target server with nothing but Node.js: no npm install there, nothing fetched at run time.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "packages", "deploy", "agent", "pso-agent.mjs");
mkdirSync(dirname(out), { recursive: true });
await build({
  entryPoints: [join(root, "packages", "deploy", "src", "agent", "main.ts")],
  outfile: out, bundle: true, platform: "node", format: "esm", target: "node24", minify: false, sourcemap: false, legalComments: "none",
  banner: { js: "#!/usr/bin/env node\n// PSO runtime agent. Generated by scripts/bundle-agent.mjs: do not edit." },
  logLevel: "warning",
});
const sum = createHash("sha256").update(readFileSync(out)).digest("hex");
writeFileSync(join(root, "packages", "deploy", "agent", "pso-agent.sha256"), `${sum}  pso-agent.mjs\n`);
console.log(`agent bundle: ${out}\nsha256 ${sum}`);
