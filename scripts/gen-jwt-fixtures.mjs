#!/usr/bin/env node
/**
 * Generates fixtures/contracts/jwt/cases.json: pre-signed tokens that the TypeScript orchestrator and the Spring starters must judge identically.
 * The signing keys are THROWAWAY: they are created here, used once and discarded. Only the public JWK and the finished tokens are written,
 * so no private key material is ever committed. Far-future / far-past timestamps keep the fixture valid without clock tricks.
 *
 *   node scripts/gen-fixtures/contracts/jwt.mjs        (rewrites fixtures/contracts/jwt/cases.json; commit the result)
 */
import { SignJWT, generateKeyPair, exportJWK, exportSPKI } from "jose";
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ISS = "https://idp.test", AUD = "pso-api", KID = "conformance-1";
const FUTURE = 4102444800;          // 2100-01-01
const PAST = 1000000000;            // 2001-09-09
const trusted = await generateKeyPair("ES256", { extractable: true });
const other = await generateKeyPair("ES256", { extractable: true });
const jwk = { ...(await exportJWK(trusted.publicKey)), kid: KID, alg: "ES256", use: "sig" };
const b64 = (o) => Buffer.from(JSON.stringify(o)).toString("base64url");

async function token(opts = {}) {
  const { iss = ISS, aud = AUD, sub = "user-1", exp = FUTURE, nbf, key = trusted.privateKey, kid = KID, claims = {} } = opts;
  const jwt = new SignJWT({ scope: "customers:read", roles: ["admin"], ...claims }).setProtectedHeader({ alg: "ES256", kid }).setExpirationTime(exp);
  if (iss !== null) jwt.setIssuer(iss);
  if (aud !== null) jwt.setAudience(aud);
  if (sub !== null) jwt.setSubject(sub);
  if (nbf !== undefined) jwt.setNotBefore(nbf);
  return jwt.sign(key);
}

const cases = [
  { name: "valid token", token: await token(), authenticated: true },
  { name: "audience is a list that contains ours", token: await token({ aud: ["other-api", AUD] }), authenticated: true },
  { name: "expired", token: await token({ exp: PAST }), authenticated: false },
  { name: "not valid yet (nbf in the future)", token: await token({ nbf: FUTURE }), authenticated: false },
  { name: "wrong issuer", token: await token({ iss: "https://evil.test" }), authenticated: false },
  { name: "issuer differs by a trailing slash", token: await token({ iss: ISS + "/" }), authenticated: false },
  { name: "wrong audience", token: await token({ aud: "other-api" }), authenticated: false },
  { name: "audience list without ours", token: await token({ aud: ["a", "b"] }), authenticated: false },
  { name: "missing issuer", token: await token({ iss: null }), authenticated: false },
  { name: "missing audience", token: await token({ aud: null }), authenticated: false },
  { name: "missing subject", token: await token({ sub: null }), authenticated: false },
  { name: "empty subject", token: await token({ sub: "" }), authenticated: false },
  { name: "signed by another key", token: await token({ key: other.privateKey }), authenticated: false },
  { name: "key id the JWKS does not publish", token: await token({ kid: "unknown-kid" }), authenticated: false },
  { name: "alg none", token: `${b64({ alg: "none", typ: "JWT" })}.${b64({ iss: ISS, aud: AUD, sub: "x", exp: FUTURE })}.`, authenticated: false },
  { name: "HS256 token", token: `${b64({ alg: "HS256", typ: "JWT", kid: KID })}.${b64({ iss: ISS, aud: AUD, sub: "x", exp: FUTURE })}.${Buffer.from("not-a-real-signature").toString("base64url")}`, authenticated: false },
  { name: "not a JWT", token: "not.a.jwt", authenticated: false },
  { name: "garbage", token: "abc", authenticated: false },
];

const doc = {
  description: "Language-neutral JWT cases. The TypeScript verifier (packages/cli/test/conformance.test.ts) and the Spring starter (JwtConformanceTests) must reach the same verdict for every case. Generated by scripts/gen-fixtures/contracts/jwt.mjs with throwaway keys; no private key is stored.",
  issuer: ISS, audience: AUD, algorithms: ["ES256"], jwks: { keys: [jwk] }, publicKeyPem: await exportSPKI(trusted.publicKey), cases,
};
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "fixtures/contracts/jwt");
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "cases.json"), JSON.stringify(doc, null, 2) + "\n");
console.log(`wrote ${cases.length} cases`);
