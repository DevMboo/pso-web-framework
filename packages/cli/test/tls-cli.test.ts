import { test, after } from "node:test";
import assert from "node:assert/strict";
import { X509Certificate } from "node:crypto";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import https from "node:https";
import { join } from "node:path";
import { createDevCertificate, describeCertificate } from "@pso/core";
import { TlsMaterial } from "@pso/http";
import { pso, tmp } from "./helpers.ts";

/**
 * TLS-01 and CFG-01 in the CLI: development certificates are created only when asked for (`pso tls:init --dev`), verified by
 * `pso tls:check`, and `pso docker:init` generates TLS between the orchestrator and the services unless plain HTTP is chosen
 * explicitly (`--transport plaintext`). Nothing here disables certificate verification, and no key is shipped: every key in these
 * tests is generated by the test run.
 */
const dirs: string[] = [];
after(() => { for (const d of dirs) { try { rmSync(d, { recursive: true, force: true, maxRetries: 8, retryDelay: 250 }); } catch { /* OS reaps temp */ } } });

async function workspace(): Promise<string> {
  const base = tmp("pso-tls-"); dirs.push(base);
  assert.equal((await pso(base, "create", "workspace", "w")).code, 0);
  const root = join(base, "w");
  assert.equal((await pso(root, "create", "orchestrator", "gw", "--structure", "legacy")).code, 0);
  assert.equal((await pso(root, "create", "service", "catalog", "--structure", "legacy", "--port", "8081")).code, 0);
  assert.equal((await pso(root, "create", "service", "orders", "--structure", "legacy", "--port", "8082")).code, 0);
  return root;
}
const read = (...p: string[]) => readFileSync(join(...p), "utf8");

test("the development certificate generator produces a real chain: verified by Node's TLS, usable by a server, refused when untrusted, misnamed or expired", async () => {
  const ca = createDevCertificate({ commonName: "test authority, with a comma", ca: true });
  const leaf = createDevCertificate({ commonName: "catalog", names: ["catalog", "localhost", "127.0.0.1"], issuer: ca });
  const x = new X509Certificate(leaf.certPem), a = new X509Certificate(ca.certPem);
  assert.deepEqual([x.checkIssued(a), x.verify(a.publicKey), a.ca, x.ca], [true, true, true, false]);
  assert.deepEqual(describeCertificate(leaf.certPem, leaf.keyPem).names, ["catalog", "localhost", "127.0.0.1"]);
  assert.equal(describeCertificate(leaf.certPem, ca.keyPem).matchesKey, false);
  const serve = async (cert: { certPem: string; keyPem: string }) => { const s = https.createServer({ cert: cert.certPem, key: cert.keyPem }, (_q, r) => r.end("ok")); await new Promise<void>((r) => s.listen(0, "127.0.0.1", () => r())); return s; };
  const get = (s: https.Server, o: https.RequestOptions) => new Promise<string>((res) => { https.get({ host: "127.0.0.1", port: (s.address() as { port: number }).port, agent: false, ...o }, (r) => { r.resume(); res(String(r.statusCode)); }).on("error", (e: NodeJS.ErrnoException) => res(e.code ?? e.message)); });
  const good = await serve(leaf);
  const expired = await serve(createDevCertificate({ commonName: "catalog", names: ["catalog", "127.0.0.1"], issuer: ca, notBefore: new Date(Date.now() - 2 * 86_400_000), notAfter: new Date(Date.now() - 86_400_000) }));
  try {
    assert.equal(await get(good, { ca: ca.certPem, servername: "catalog" }), "200", "trusted authority, expected name");
    assert.equal(await get(good, { servername: "catalog" }), "UNABLE_TO_VERIFY_LEAF_SIGNATURE", "no trust configured");
    assert.equal(await get(good, { ca: createDevCertificate({ commonName: "other", ca: true }).certPem, servername: "catalog" }), "UNABLE_TO_VERIFY_LEAF_SIGNATURE", "another authority");
    assert.equal(await get(good, { ca: ca.certPem, servername: "billing" }), "ERR_TLS_CERT_ALTNAME_INVALID", "wrong name");
    assert.equal(await get(expired, { ca: ca.certPem, servername: "catalog" }), "CERT_HAS_EXPIRED");
  } finally { good.close(); expired.close(); }
});

test("pso tls:init creates development certificates only when --dev is given, for every service, idempotently; pso tls:check verifies them", async () => {
  const root = await workspace();
  const refused = await pso(root, "tls:init");
  assert.equal(refused.code, 1);
  assert.match(refused.err + refused.out, /development certificates only: pass --dev/);
  assert.equal(existsSync(join(root, "tls")), false, "nothing is created without the explicit choice");
  assert.match((await pso(root, "tls:check")).err, /No TLS directory/);

  const first = await pso(root, "tls:init", "--dev", "--hosts", "idp");
  assert.equal(first.code, 0, first.err);
  assert.match(first.out, /DEVELOPMENT certificates for catalog, orders, idp/);
  for (const f of ["ca.crt", "ca.key", "README.txt", "catalog/tls.crt", "catalog/tls.key", "catalog/ca.crt", "orders/tls.crt", "idp/tls.crt"]) assert.ok(existsSync(join(root, "tls", ...f.split("/"))), f);
  assert.match(read(root, "tls", "README.txt"), /DEVELOPMENT CERTIFICATES\. NOT FOR PRODUCTION\./);
  assert.ok(read(root, ".gitignore").split(/\r?\n/).includes("tls/"), "the keys are kept out of version control");
  const cat = describeCertificate(read(root, "tls", "catalog", "tls.crt"), read(root, "tls", "catalog", "tls.key"));
  assert.deepEqual([cat.names, cat.matchesKey, cat.ca, cat.expired], [["catalog", "localhost"], true, false, false], "named after the service: the DNS name the orchestrator connects to in Compose");
  assert.match(cat.issuer, /PSO development CA for w - not for production/);
  // each run of the generator makes its own keys: nothing is shared between workspaces, nothing is embedded in the CLI
  const other = await workspace();
  assert.equal((await pso(other, "tls:init", "--dev")).code, 0);
  assert.notEqual(read(other, "tls", "ca.key"), read(root, "tls", "ca.key"));
  assert.notEqual(read(other, "tls", "catalog", "tls.key"), read(root, "tls", "catalog", "tls.key"));

  const check = JSON.parse((await pso(root, "tls:check", "--hosts", "idp", "--json")).out) as { ok: boolean; certificates: Array<{ name: string }>; findings: unknown[] };
  assert.deepEqual([check.ok, check.certificates.map((c) => c.name), check.findings], [true, ["ca.crt", "catalog", "orders", "idp"], []]);
  assert.doesNotMatch((await pso(root, "tls:check")).out, /PRIVATE KEY|BEGIN/, "no key material is printed");
  // idempotent: the authority and the valid certificates are kept
  const caBefore = read(root, "tls", "ca.crt"), leafBefore = read(root, "tls", "catalog", "tls.crt");
  const again = await pso(root, "tls:init", "--dev", "--hosts", "idp");
  assert.match(again.out, /unchanged {2}tls\/ca\.crt/); assert.match(again.out, /unchanged {2}tls\/catalog\/tls\.crt/);
  assert.deepEqual([read(root, "tls", "ca.crt"), read(root, "tls", "catalog", "tls.crt")], [caBefore, leafBefore]);
  // a service added later gets a certificate from the same authority
  assert.equal((await pso(root, "create", "service", "billing", "--structure", "legacy", "--port", "8083")).code, 0);
  assert.match((await pso(root, "tls:check")).out, /ERROR {3}billing: billing\/tls\.crt is missing/);
  assert.match((await pso(root, "tls:init", "--dev")).out, /created {4}tls\/billing\/tls\.crt/);
  assert.equal(read(root, "tls", "ca.crt"), caBefore);
  assert.equal((await pso(root, "tls:check")).code, 0);
});

test("pso tls:check names what is wrong with supplied certificates: expired, wrong name, another authority, a key that does not match, a missing file", async () => {
  const root = await workspace();
  assert.equal((await pso(root, "tls:init", "--dev")).code, 0);
  const ca = { certPem: read(root, "tls", "ca.crt"), keyPem: read(root, "tls", "ca.key") };
  const put = (svc: string, c: { certPem: string; keyPem: string }) => { writeFileSync(join(root, "tls", svc, "tls.crt"), c.certPem); writeFileSync(join(root, "tls", svc, "tls.key"), c.keyPem); };
  const problems = async () => { const r = await pso(root, "tls:check"); return { code: r.code, out: r.out }; };

  put("catalog", createDevCertificate({ commonName: "catalog", names: ["catalog", "localhost"], issuer: ca, notBefore: new Date(Date.now() - 3 * 86_400_000), notAfter: new Date(Date.now() - 86_400_000) }));
  let p = await problems();
  assert.equal(p.code, 1); assert.match(p.out, /ERROR {3}catalog: the certificate expired on \d{4}-\d\d-\d\d/); assert.match(p.out, /FAILED: 1 problem/);
  put("catalog", createDevCertificate({ commonName: "catalog", names: ["catalog", "localhost"], issuer: ca, notAfter: new Date(Date.now() + 10 * 86_400_000) }));
  p = await problems();
  assert.equal(p.code, 0, "about to expire is a warning, not a failure"); assert.match(p.out, /WARNING catalog: the certificate expires in \d+ day/);
  put("catalog", createDevCertificate({ commonName: "something-else", names: ["something-else"], issuer: ca }));
  p = await problems();
  assert.match(p.out, /ERROR {3}catalog: the certificate does not name "catalog" \(subject alternative names: something-else\)/);
  put("catalog", createDevCertificate({ commonName: "catalog", names: ["catalog", "localhost"], issuer: createDevCertificate({ commonName: "another authority", ca: true }) }));
  assert.match((await problems()).out, /ERROR {3}catalog: the certificate was not issued by the authority in ca\.crt/);
  const good = createDevCertificate({ commonName: "catalog", names: ["catalog", "localhost"], issuer: ca });
  put("catalog", { certPem: good.certPem, keyPem: createDevCertificate({ commonName: "x" }).keyPem });
  assert.match((await problems()).out, /ERROR {3}catalog: the private key does not belong to the certificate/);
  put("catalog", good);
  assert.equal((await problems()).code, 0);
  rmSync(join(root, "tls", "orders", "tls.key"));
  assert.match((await problems()).out, /ERROR {3}orders: orders\/tls\.key is missing/);
  // an existing directory that is not ours (an authority without its key) is not overwritten by tls:init
  rmSync(join(root, "tls", "ca.key"));
  const init = await pso(root, "tls:init", "--dev");
  assert.equal(init.code, 1); assert.match(init.err + init.out, /exists without its key: these are not development certificates created here/);
  assert.equal(read(root, "tls", "ca.crt"), ca.certPem);
});

test("pso docker:init generates TLS between the orchestrator and every service by default; plain HTTP only with --transport plaintext", async () => {
  const root = await workspace();
  // secure default, before any certificate exists: the compose file is generated for TLS and says what is missing
  const init = await pso(root, "docker:init");
  assert.equal(init.code, 0, init.err);
  assert.match(init.out, /NOTE {7}TLS: gw -> catalog, orders uses HTTPS with certificates from \.\/tls \(PSO_TLS_DIR\), which does not exist yet\. Development: `pso tls:init --dev`/);
  const dc = read(root, "docker-compose.yml").replaceAll("\r\n", "\n");
  for (const s of ["CATALOG", "ORDERS"]) { assert.ok(dc.includes(`PSO_UPSTREAM_${s}_TLS: "true"`), s); assert.ok(dc.includes(`PSO_UPSTREAM_${s}_TLS_CA_FILE: /run/pso/tls/ca.crt`), s); }
  assert.doesNotMatch(dc, /ALLOW_PLAINTEXT/, "no plaintext authorization is generated unless it is asked for");
  // the service's endpoint prefix travels with its address (the workspace file is not in the image), so a forwarded path reaches /catalog/...
  assert.ok(dc.includes('PSO_UPSTREAM_CATALOG_PREFIX: "/catalog"') && dc.includes('PSO_UPSTREAM_ORDERS_PREFIX: "/orders"'));
  assert.doesNotMatch(dc, /NODE_TLS_REJECT_UNAUTHORIZED|rejectUnauthorized|verify=false|insecure|-k /i, "nothing disables verification");
  for (const [s, port] of [["catalog", 8081], ["orders", 8082]] as const) {
    assert.ok(dc.includes(`      - \${PSO_TLS_DIR:-./tls}/${s}:/run/pso/tls:ro`), "each service mounts only its own certificate directory, read-only");
    assert.ok(dc.includes(`curl -fsS --cacert /run/pso/tls/ca.crt https://localhost:${port}/actuator/health`), "the health check verifies the certificate too");
  }
  assert.equal((dc.match(/SERVER_SSL_CERTIFICATE: file:\/run\/pso\/tls\/tls\.crt/g) ?? []).length, 2);
  assert.equal((dc.match(/SERVER_SSL_CERTIFICATE_PRIVATE_KEY: file:\/run\/pso\/tls\/tls\.key/g) ?? []).length, 2);
  assert.ok(dc.includes("      - ${PSO_TLS_DIR:-./tls}/ca.crt:/run/pso/tls/ca.crt:ro"), "the orchestrator mounts the authority only, never a service key");
  assert.doesNotMatch(dc.slice(dc.indexOf("\n  gw:")), /tls\.key/);
  // the identity provider settings travel through .env, empty by default
  for (const l of ["PSO_JWT_JWKS_PRIVATE_HOSTS: ${PSO_JWT_JWKS_PRIVATE_HOSTS:-}", "PSO_JWT_JWKS_CA_FILE: ${PSO_JWT_JWKS_CA_FILE:-}", "PSO_SECURITY_JWT_CA_FILE: ${PSO_JWT_JWKS_CA_FILE:-}"]) assert.ok(dc.includes(l), l);
  const example = read(root, ".env.example");
  for (const l of ["# PSO_JWT_JWKS_PRIVATE_HOSTS=idp:8443", "# PSO_JWT_JWKS_CA_FILE=/run/pso/tls/ca.crt", "# PSO_TLS_DIR=./tls"]) assert.ok(example.includes(l), l);
  // with certificates in place the generator verifies them and says so; a broken one is reported at generation time
  assert.equal((await pso(root, "tls:init", "--dev")).code, 0);
  assert.match((await pso(root, "docker:init")).out, /NOTE {7}TLS: gw -> catalog, orders over HTTPS, certificates from \.\/tls verified \(authority, validity, host names\)/);
  rmSync(join(root, "tls", "orders", "tls.crt"));
  assert.match((await pso(root, "docker:init")).out, /WARNING {4}TLS: orders: orders\/tls\.crt is missing/);

  // the explicit legacy / development choice
  assert.match((await pso(root, "docker:init", "--transport", "http")).err, /Unknown --transport "http"/);
  const conflict = await pso(root, "docker:init", "--transport", "plaintext");
  assert.equal(conflict.code, 1, "an existing compose file is never replaced silently");
  const plain = await pso(root, "docker:init", "--transport", "plaintext", "--force");
  assert.equal(plain.code, 0);
  assert.match(plain.out, /NOTE {7}gw -> catalog: plain HTTP on the private compose network, authorized for this upstream only/);
  const dp = read(root, "docker-compose.yml");
  assert.ok(dp.includes('PSO_UPSTREAM_CATALOG_ALLOW_PLAINTEXT: "${PSO_UPSTREAM_CATALOG_ALLOW_PLAINTEXT:-true}"'));
  assert.doesNotMatch(dp, /_TLS: "true"|SERVER_SSL_CERTIFICATE/);
});

test("an expired or not yet valid certificate authority is named when the orchestrator loads its upstream TLS settings", () => {
  const base = tmp("pso-tls-mat-"); dirs.push(base);
  const write = (n: string, t: string) => { const f = join(base, n); writeFileSync(f, t); return f; };
  const current = write("ca.crt", createDevCertificate({ commonName: "current", ca: true }).certPem);
  const expired = write("old.crt", createDevCertificate({ commonName: "old", ca: true, notBefore: new Date(Date.now() - 3 * 86_400_000), notAfter: new Date(Date.now() - 86_400_000) }).certPem);
  const future = write("future.crt", createDevCertificate({ commonName: "future", ca: true, notBefore: new Date(Date.now() + 86_400_000), notAfter: new Date(Date.now() + 5 * 86_400_000) }).certPem);
  const soon = write("soon.crt", createDevCertificate({ commonName: "soon", ca: true, notAfter: new Date(Date.now() + 9 * 86_400_000 + 3_600_000) }).certPem);
  const ok = new TlsMaterial({ caFile: current }, "catalog"); ok.init();
  assert.ok((ok.daysLeft ?? 0) > 300);
  assert.throws(() => new TlsMaterial({ caFile: expired }, "catalog").init(), /the certificate authority in .*old\.crt expired on \d{4}-\d\d-\d\d/);
  assert.throws(() => new TlsMaterial({ caFile: future }, "catalog").init(), /is not valid before \d{4}-\d\d-\d\d/);
  const s = new TlsMaterial({ caFile: soon }, "catalog"); s.init();
  assert.equal(s.daysLeft, 9, "what the start-up warning reports");
  assert.throws(() => new TlsMaterial({ caFile: join(base, "missing.crt") }, "catalog").init(), /TLS file not found/);
});
