/**
 * PSO Storage on the CLI side: opt a Spring service into storage (`storage:enable`), check its configuration before it runs
 * (`storage:validate`) and generate the files controller and its test (`make:files`). Upload DTOs, upload routes and download routes of the
 * orchestrator are generated by the existing `make:dto --fields name:file:...` and `make:route --upstream ... [--download]`.
 */
const PROVIDERS = ["local", "s3", "azure"] as const;
type Provider = (typeof PROVIDERS)[number];

const dep = (group: string, artifact: string, extra = ""): string => `    <dependency>\n      <groupId>${group}</groupId>\n      <artifactId>${artifact}</artifactId>\n${extra}    </dependency>\n`;
const STORAGE_STARTER = dep("com.pso", "pso-storage-spring-boot-starter");
const S3_DEPS: Array<[string, string]> = [["s3", dep("software.amazon.awssdk", "s3")]];
const AZURE_DEPS: Array<[string, string]> = [["azure-storage-blob", dep("com.azure", "azure-storage-blob")], ["azure-identity", dep("com.azure", "azure-identity")]];

function springService(ctx: Ctx) {
  const { root, config } = requireWorkspace(ctx);
  const springs = config.services.filter((s) => s.runtime === "spring-boot");
  const name = str(ctx.flags["service"]) ?? (springs.length === 1 ? springs[0]!.name : undefined);
  const svc = springs.find((s) => s.name === name);
  if (!svc) throw new CliError("Name the Spring service with --service", `Spring services: ${springs.map((s) => s.name).join(", ") || "(none)"}`);
  return { root, svc, dir: join(root, ...svc.path.split("/")) };
}

/** The pso.storage block written into application.yml. Secrets never appear: S3 uses the AWS credential chain, Azure a managed identity. */
export function storageYaml(provider: Provider, o: { root?: string; bucket?: string; region?: string; container?: string; endpoint?: string; maxSize?: string }): string {
  const lines = [
    "  storage:                     # PSO Storage (`pso storage:enable`): files behind one API, private by default. Reference: Spring > Storage.",
    `    provider: ${provider}`,
  ];
  if (provider === "local") lines.push("    local:", `      root: \${PSO_STORAGE_ROOT:${o.root ?? "./storage"}}   # created with owner-only permissions; keep it OUTSIDE any served directory`);
  if (provider === "s3") lines.push("    s3:", `      bucket: ${o.bucket ?? "${PSO_STORAGE_S3_BUCKET:}"}`, `      region: ${o.region ?? "${AWS_REGION:}"}`, "      prefix: ${PSO_STORAGE_S3_PREFIX:}", "      # credentials: the AWS default provider chain (role, profile, environment). Never put keys here; buckets are private.");
  if (provider === "azure") lines.push("    azure:", `      endpoint: ${o.endpoint ?? "${PSO_STORAGE_AZURE_ENDPOINT:}"}   # https://<account>.blob.core.windows.net, authenticated with a managed identity (DefaultAzureCredential)`, `      container: ${o.container ?? "${PSO_STORAGE_AZURE_CONTAINER:}"}`, "      prefix: ${PSO_STORAGE_AZURE_PREFIX:}");
  lines.push("    upload:", `      max-size: ${o.maxSize ?? "5MB"}              # keep <= pso.limits.multipart.max-file-size`, "      # allowed-content-types: [application/pdf]   # restrict per service; known formats are always verified by signature", "    # signed-url: { enabled: false }               # S3 / Azure only, short-lived, opt in", "    # scan: { required: false }                    # true needs a ContentScanner bean (no scanning engine is included)");
  return lines.join("\n") + "\n";
}

/** Inserts `block` into the pso: section just before the `  database:` key, or replaces the provider value of an existing storage block. */
export function applyStorageBlock(yml: string, provider: Provider, block: string): { text: string; changed: boolean; note: string } {
  const existing = /^(  storage:[^\n]*\n(?:(?:    |      )[^\n]*\n|\s*\n)*?    provider: )([A-Za-z0-9]+)([^\n]*)$/m.exec(yml);
  if (existing) {
    if (existing[2] === provider) return { text: yml, changed: false, note: "" };
    return { text: yml.replace(existing[0], `${existing[1]}${provider}${existing[3]}`), changed: true, note: `pso.storage.provider = ${provider} (add the ${provider} settings by hand: the existing storage block was kept)` };
  }
  const at = yml.search(/^  database:/m);
  if (at < 0) throw new CliError("application.yml has no pso.database section to anchor the storage settings", "Add the pso.storage block from the documentation by hand");
  return { text: yml.slice(0, at) + block + yml.slice(at), changed: true, note: `application.yml: + pso.storage (provider ${provider})` };
}

function addToProfile(dir: string, file: string, provider: Provider, rootDir: string, edits: Array<[string, string, string]>, changes: string[], why: string): void {
  const f = join(dir, "src/main/resources", file);
  if (!existsSync(f)) return;
  const before = readFileSync(f, "utf8");
  if (/^  storage:/m.test(before)) return;
  const add = `  storage:                     # ${why}\n    provider: ${provider}\n    local:\n      root: ${rootDir}\n`;
  const after = /^pso:\n/m.test(before) ? before.replace(/^pso:\n/m, `pso:\n${add}`) : before.replace(/\n*$/, "\n") + `pso:\n${add}`;
  edits.push([f, before, after]);
  changes.push(`${file}: local filesystem storage (${why})`);
}

export function validateStorageSize(v: string): void {
  try { parseSize(v); } catch { throw new CliError(`Invalid --max-size "${v}"`, "Use a value such as 5MB or 512KB"); }
}

