/**
 * `pso idp:dev`: a DEVELOPMENT identity provider for a workspace, so that the secure paths of an application (JWT validation in
 * the orchestrator and in every Spring service, scopes, roles, the private-network approval of the JWKS endpoint, its certificate
 * authority) can be exercised on a developer's machine without an account at a real provider and without any test fixture of the
 * framework.
 *
 *   init    generates a signing key pair ON THIS MACHINE (never shipped, never reused), the public key set (jwks.json), a small
 *           dependency-free JWKS server (dev-idp.cjs) and a Compose overlay (docker-compose.idp.yml) that runs it next to the
 *           generated deployment. The server holds PUBLIC keys only: the private key never enters a container or an image.
 *   token   signs a JWT with that key for a synthetic identity (subject, scopes, roles), on the host.
 *   serve   runs the JWKS server on loopback over plain HTTP for `pso dev` (both runtimes accept an http JWKS URI on loopback
 *           outside production).
 *
 * It is not an identity provider for any real use: there are no users, no login and no revocation. Three things keep it out of
 * production: the commands refuse to run with PSO_ENV=production, `pso security:check --env production` reports a configuration
 * that names this issuer (SEC013), and the Compose overlay is a separate file that a production deployment does not include.
 */
export const IDP_DIR = "idp";
export const IDP_COMPOSE = "docker-compose.idp.yml";
const SERVER_FILE = "dev-idp.cjs";

interface IdpConfig { comment: string; issuer: string; audience: string; kid: string; alg: "ES256"; host: string; port: number; createdAt: string }

const b64 = (b: Buffer | string): string => Buffer.from(b).toString("base64url");

/** A compact JWS (ES256) signed with the development key. */
export function signDevToken(privateKeyPem: string, kid: string, claims: Record<string, unknown>): string {
  const head = b64(JSON.stringify({ alg: "ES256", typ: "JWT", kid }));
  const body = b64(JSON.stringify(claims));
  const sig = sign("sha256", Buffer.from(`${head}.${body}`), { key: createPrivateKey(privateKeyPem), dsaEncoding: "ieee-p1363" });
  return `${head}.${body}.${b64(sig)}`;
}

const SERVER = `// DEVELOPMENT ONLY. Generated by \`pso idp:dev init\`. NOT an identity provider for any real use.
//
// It publishes the PUBLIC keys of the development issuer of this workspace (jwks.json next to this file) so that the orchestrator
// and the services can validate the tokens that \`pso idp:dev token\` signs on the developer's machine. It holds no private key, has
// no users, no login and no token endpoint. Never deploy it and never point a production configuration at it.
//
//   env: IDP_PORT (default 8443)  IDP_HOST (default 0.0.0.0 with TLS, 127.0.0.1 without)
//        IDP_CERT, IDP_KEY (PEM files): HTTPS. Without them it serves plain HTTP and binds loopback only.
//   GET /.well-known/jwks.json   the public keys        GET /healthz
"use strict";
const fs = require("node:fs");
const path = require("node:path");
const tls = !!(process.env.IDP_CERT && process.env.IDP_KEY);
const jwksFile = path.join(__dirname, "jwks.json");
const handler = (req, res) => {
  const send = (status, text) => { res.writeHead(status, { "content-type": "application/json", "content-length": Buffer.byteLength(text), "cache-control": "no-store", "x-content-type-options": "nosniff" }); res.end(text); };
  if (req.method === "GET" && req.url === "/.well-known/jwks.json") { try { return send(200, fs.readFileSync(jwksFile, "utf8")); } catch { return send(500, JSON.stringify({ error: "jwks.json is not readable" })); } }
  if (req.method === "GET" && req.url === "/healthz") return send(200, JSON.stringify({ status: "UP", kind: "development identity provider, not for production" }));
  send(404, JSON.stringify({ error: "not found" }));
};
const server = tls
  ? require("node:https").createServer({ cert: fs.readFileSync(process.env.IDP_CERT), key: fs.readFileSync(process.env.IDP_KEY) }, handler)
  : require("node:http").createServer(handler);
const port = Number(process.env.IDP_PORT || 8443);
const host = process.env.IDP_HOST || (tls ? "0.0.0.0" : "127.0.0.1");
server.listen(port, host, () => console.log("pso development identity provider (NOT for production): " + (tls ? "https" : "http") + "://" + host + ":" + port + "/.well-known/jwks.json"));
for (const s of ["SIGTERM", "SIGINT"]) process.on(s, () => server.close(() => process.exit(0)));
`;

/** The overlay that runs the JWKS server next to the generated deployment. A separate file on purpose: production never includes it. */
export function idpCompose(ws: WorkspaceConfig, cfg: Pick<IdpConfig, "host" | "port">): string {
  const dependents = ws.services.map((s) => s.name);
  return [
    "# DEVELOPMENT ONLY. Generated by `pso idp:dev init`: the development identity provider of this workspace.",
    "# Use it together with the generated deployment:",
    `#   docker compose -f docker-compose.yml -f ${IDP_COMPOSE} up -d --wait`,
    "# It serves the PUBLIC keys of ./idp/jwks.json over HTTPS with the certificate of ./tls/" + cfg.host + " (pso tls:init --dev --hosts " + cfg.host + ").",
    "# The private signing key stays on this machine (./idp/keys, git-ignored) and is never mounted. A production deployment does not",
    "# include this file and points PSO_JWT_* at the real identity provider.",
    "services:",
    `  ${cfg.host}:`,
    "    image: node:24-alpine",
    `    command: ["node", "/idp/${SERVER_FILE}"]`,
    "    environment:",
    `      IDP_PORT: "${cfg.port}"`,
    "      IDP_CERT: /run/pso/tls/tls.crt",
    "      IDP_KEY: /run/pso/tls/tls.key",
    "    volumes:",
    `      - ./${IDP_DIR}/${SERVER_FILE}:/idp/${SERVER_FILE}:ro`,
    `      - ./${IDP_DIR}/jwks.json:/idp/jwks.json:ro`,
    `      - \${PSO_TLS_DIR:-./tls}/${cfg.host}:/run/pso/tls:ro`,
    '    user: "${PSO_CONTAINER_USER:-1000:1000}"',
    "    healthcheck:",
    `      test: ["CMD", "node", "-e", "require('node:https').get({host:'localhost',port:${cfg.port},path:'/healthz',ca:require('node:fs').readFileSync('/run/pso/tls/ca.crt')},r=>process.exit(r.statusCode===200?0:1)).on('error',()=>process.exit(1))"]`,
    "      interval: 5s",
    "      timeout: 3s",
    "      retries: 10",
    "    read_only: true",
    "    cap_drop:",
    "      - ALL",
    "    security_opt:",
    "      - no-new-privileges:true",
    "    networks:",
    "      - internal",
    ...dependents.flatMap((n) => [`  ${n}:`, "    depends_on:", `      ${cfg.host}:`, "        condition: service_healthy"]),
    "",
  ].join("\n");
}

const refuseProduction = (): void => {
  if ((process.env["PSO_ENV"] ?? process.env["NODE_ENV"]) === "production") throw new CliError("`pso idp:dev` is a development tool and does not run with PSO_ENV=production", "Production uses a real identity provider: set PSO_JWT_ISSUER, PSO_JWT_AUDIENCE and PSO_JWT_JWKS_URI to it");
};

const dirOf = (root: string, ctx: Ctx): { dir: string; rel: string } => {
  const rel = str(ctx.flags["dir"]) ?? IDP_DIR;
  if (!/^[A-Za-z0-9._-]+(\/[A-Za-z0-9._-]+)*$/.test(rel) || rel.split("/").includes("..")) throw new CliError(`Invalid --dir "${rel}"`, "Use a folder inside the workspace, e.g. idp");
  return { dir: join(root, ...rel.split("/")), rel };
};

export function readIdpConfig(dir: string): IdpConfig | undefined {
  try { return JSON.parse(readFileSync(join(dir, "idp.json"), "utf8")) as IdpConfig; } catch { return undefined; }
}

function ensureIgnored(root: string, line: string): boolean {
  const gi = join(root, ".gitignore");
  const cur = existsSync(gi) ? readFileSync(gi, "utf8") : "";
  if (cur.split(/\r?\n/).includes(line)) return false;
  writeFileSync(gi, `${cur}${cur.endsWith("\n") || cur === "" ? "" : "\n"}${line}\n`);
  return true;
}

function init(ctx: Ctx): number {
  refuseProduction();
  const { root, config } = requireWorkspace(ctx);
  const { dir, rel } = dirOf(root, ctx);
  const dry = ctx.flags["dry-run"] === true, force = ctx.flags["force"] === true;
  const host = str(ctx.flags["host"]) ?? "idp";
  if (!/^[a-z][a-z0-9-]{0,40}$/.test(host)) throw new CliError(`Invalid --host "${host}"`, "Use the name of the identity provider's container, e.g. idp");
  if (config.services.some((s) => s.name === host)) throw new CliError(`"${host}" is already a service of this workspace`, "Choose another --host for the identity provider");
  const portRaw = str(ctx.flags["port"]) ?? "8443";
  if (!/^\d{2,5}$/.test(portRaw) || Number(portRaw) < 1 || Number(portRaw) > 65535) throw new CliError(`Invalid --port "${portRaw}"`);
  const port = Number(portRaw);
  const issuer = str(ctx.flags["issuer"]) ?? `https://${host}:${port}`;
  let issuerUrl: URL;
  try { issuerUrl = new URL(issuer); } catch { throw new CliError(`Invalid --issuer "${issuer}"`, "Use an https URL, e.g. https://idp:8443"); }
  if (issuerUrl.protocol !== "https:" && !(issuerUrl.protocol === "http:" && /^(localhost|127\.0\.0\.1)$/.test(issuerUrl.hostname))) throw new CliError("--issuer must be an https URL (http is accepted for localhost only)");
  const audience = str(ctx.flags["audience"]) ?? "pso-api";
  if (!/^[A-Za-z0-9._:/-]{1,200}$/.test(audience)) throw new CliError(`Invalid --audience "${audience}"`);
  const existing = readIdpConfig(dir);
  if (existing && !force) throw new CliError(`${rel}/idp.json already exists (issuer ${existing.issuer})`, "The development issuer of this workspace is already set up. Use --force to replace it with a NEW key (tokens signed with the old one stop validating)");

  const kid = `dev-${new Date().toISOString().slice(0, 10).replace(/-/g, "")}-${randomBytes(4).toString("hex")}`;
  const pair = generateKeyPairSync("ec", { namedCurve: "P-256", publicKeyEncoding: { type: "spki", format: "pem" }, privateKeyEncoding: { type: "pkcs8", format: "pem" } });
  const jwk = { ...createPublicKey(pair.publicKey).export({ format: "jwk" }), kid, alg: "ES256", use: "sig" };
  const cfg: IdpConfig = { comment: "DEVELOPMENT identity provider of this workspace (pso idp:dev). Never used in production.", issuer, audience, kid, alg: "ES256", host, port, createdAt: new Date().toISOString() };
  const files: Array<[rel: string, text: string, mode: number]> = [
    [`${rel}/idp.json`, JSON.stringify(cfg, null, 2) + "\n", 0o644],
    [`${rel}/jwks.json`, JSON.stringify({ keys: [jwk] }, null, 2) + "\n", 0o644],
    [`${rel}/${SERVER_FILE}`, SERVER, 0o644],
    [`${rel}/keys/${kid}.private.pem`, pair.privateKey, 0o600],
    [`${rel}/keys/${kid}.public.pem`, pair.publicKey, 0o644],
    [IDP_COMPOSE, idpCompose(config, cfg), 0o644],
  ];
  // an existing overlay that was edited is never replaced silently
  const overlay = join(root, IDP_COMPOSE);
  if (existsSync(overlay) && readFileSync(overlay, "utf8") !== idpCompose(config, cfg) && !force) throw new CliError(`${IDP_COMPOSE} already exists with different content`, "Nothing was written. Use --force to replace it");
  if (!dry) {
    for (const [f, text, mode] of files) {
      const abs = join(root, ...f.split("/"));
      mkdirSync(join(abs, ".."), { recursive: true });
      writeFileSync(abs, text, { mode });
      try { chmodSync(abs, mode); } catch { /* a file system without POSIX modes (Windows): the folder's own access control applies */ }
    }
    ensureIgnored(root, `${rel}/keys/`);
  }
  const jwksUri = `${issuer.replace(/\/$/, "")}/.well-known/jwks.json`;
  const env = [`PSO_JWT_ISSUER=${issuer}`, `PSO_JWT_AUDIENCE=${audience}`, `PSO_JWT_JWKS_URI=${jwksUri}`, "PSO_JWT_ALGORITHMS=ES256", `PSO_JWT_JWKS_PRIVATE_HOSTS=${issuerUrl.host.includes(":") ? issuerUrl.host : `${issuerUrl.host}:443`}`, "PSO_JWT_JWKS_CA_FILE=/run/pso/tls/ca.crt"];
  emit(ctx, { dryRun: dry, issuer, audience, kid, jwksUri, files: files.map(([f]) => f), env }, [
    ...files.map(([f]) => `${dry ? "[dry-run] " : ""}created    ${f}`),
    `${dry ? "[dry-run] " : ""}.gitignore: ${rel}/keys/ (the private signing key stays on this machine)`,
    "",
    "DEVELOPMENT identity provider. Its key was generated here and is not used anywhere else; never configure it for production.",
    "",
    "Secure Compose deployment (after `pso docker:init`):",
    `  1. pso tls:init --dev --hosts ${host}        the certificate of the identity provider (and of the services)`,
    "  2. put these in .env:",
    ...env.map((l) => `       ${l}`),
    `  3. docker compose -f docker-compose.yml -f ${IDP_COMPOSE} up -d --wait`,
    "  4. pso idp:dev token --scopes <scope,scope>     a signed token for requests through the orchestrator",
    "",
    "Local development (`pso dev`): `pso idp:dev serve` and set PSO_JWT_JWKS_URI to the URL it prints (see the documentation).",
  ].join("\n"));
  return 0;
}

function token(ctx: Ctx): number {
  refuseProduction();
  const { root } = requireWorkspace(ctx);
  const { dir, rel } = dirOf(root, ctx);
  const cfg = readIdpConfig(dir);
  if (!cfg) throw new CliError(`No development identity provider in ${rel}/`, "Run `pso idp:dev init` first");
  const keyFile = join(dir, "keys", `${cfg.kid}.private.pem`);
  if (!existsSync(keyFile)) throw new CliError(`The signing key ${rel}/keys/${cfg.kid}.private.pem is missing`, "It exists only on the machine where `pso idp:dev init` ran. Run `pso idp:dev init --force` to create a new one here");
  const list = (name: string, pattern: RegExp): string[] => {
    const v = (str(ctx.flags[name]) ?? "").split(",").map((x) => x.trim()).filter(Boolean);
    for (const x of v) if (!pattern.test(x)) throw new CliError(`Invalid value "${x.slice(0, 60)}" in --${name}`);
    return v;
  };
  const scopes = list("scopes", /^[A-Za-z0-9:._-]+$/), roles = list("roles", /^[A-Za-z0-9:._-]+$/);
  const sub = str(ctx.flags["sub"]) ?? "dev-user";
  if (!/^[A-Za-z0-9@._:-]{1,128}$/.test(sub)) throw new CliError(`Invalid --sub "${sub.slice(0, 60)}"`);
  const ttlRaw = str(ctx.flags["ttl"]) ?? "900";
  if (!/^\d{1,6}$/.test(ttlRaw) || Number(ttlRaw) < 1 || Number(ttlRaw) > 86_400) throw new CliError(`Invalid --ttl "${ttlRaw}"`, "Seconds, from 1 to 86400 (a development token should be short-lived)");
  const audience = str(ctx.flags["audience"]) ?? cfg.audience;
  const now = Math.floor(Date.now() / 1000);
  const claims = { iss: cfg.issuer, aud: audience, sub, iat: now, nbf: now - 5, exp: now + Number(ttlRaw), jti: randomUUID(), ...(scopes.length ? { scope: scopes.join(" ") } : {}), ...(roles.length ? { roles } : {}) };
  const jwt = signDevToken(readFileSync(keyFile, "utf8"), cfg.kid, claims);
  // the token itself is the output: nothing else is printed in the plain form, so it can be used as $(pso idp:dev token ...)
  if (ctx.flags["json"] === true) ctx.print(JSON.stringify({ token: jwt, claims, kid: cfg.kid, expiresAt: new Date((now + Number(ttlRaw)) * 1000).toISOString() }, null, 2));
  else ctx.print(jwt);
  return 0;
}

async function serve(ctx: Ctx): Promise<number> {
  refuseProduction();
  const { root } = requireWorkspace(ctx);
  const { dir, rel } = dirOf(root, ctx);
  const cfg = readIdpConfig(dir);
  if (!cfg) throw new CliError(`No development identity provider in ${rel}/`, "Run `pso idp:dev init` first");
  const portRaw = str(ctx.flags["port"]) ?? "9443";
  if (!/^\d{2,5}$/.test(portRaw) || Number(portRaw) > 65535) throw new CliError(`Invalid --port "${portRaw}"`);
  const jwks = join(dir, "jwks.json");
  const server = createServer((req, res) => {
    const send = (status: number, text: string): void => { res.writeHead(status, { "content-type": "application/json", "content-length": Buffer.byteLength(text), "cache-control": "no-store", "x-content-type-options": "nosniff" }); res.end(text); };
    if (req.method === "GET" && req.url === "/.well-known/jwks.json") { try { send(200, readFileSync(jwks, "utf8")); } catch { send(500, '{"error":"jwks.json is not readable"}'); } }
    else if (req.method === "GET" && req.url === "/healthz") send(200, '{"status":"UP","kind":"development identity provider, not for production"}');
    else send(404, '{"error":"not found"}');
  });
  await new Promise<void>((resolve, reject) => { server.once("error", (e: NodeJS.ErrnoException) => reject(new CliError(`cannot listen on 127.0.0.1:${portRaw} (${e.code ?? e.name})`, "Choose another --port"))); server.listen(Number(portRaw), "127.0.0.1", () => resolve()); });
  const uri = `http://127.0.0.1:${portRaw}/.well-known/jwks.json`;
  ctx.print([
    `development identity provider (NOT for production): ${uri}`,
    "loopback only, public keys only. For `pso dev`, put in the orchestrator's and the services' .env:",
    `  PSO_JWT_ISSUER=${cfg.issuer}`, `  PSO_JWT_AUDIENCE=${cfg.audience}`, `  PSO_JWT_JWKS_URI=${uri}`, "  PSO_JWT_ALGORITHMS=ES256",
    "Press Ctrl+C to stop.",
  ].join("\n"));
  if (ctx.flags["once"] === true) { await new Promise<void>((r) => server.close(() => r())); return 0; } // start-up check for scripts and tests
  await new Promise<void>((done) => { const stop = (): void => { server.close(() => done()); }; process.once("SIGINT", stop); process.once("SIGTERM", stop); });
  return 0;
}

void servicePrefix;

export const IDP_COMMANDS: Record<string, Command> = {
  "idp:dev": {
    usage: "pso idp:dev init [--issuer https://idp:8443] [--audience pso-api] [--host idp] [--port 8443] [--dir idp] [--dry-run] [--force] [--json] | token [--sub dev-user] [--scopes a,b] [--roles x,y] [--ttl 900] [--audience pso-api] [--dir idp] [--json] | serve [--port 9443] [--dir idp] [--once]",
    summary: "DEVELOPMENT identity provider for a workspace: init generates a signing key on this machine, its public key set, a JWKS server and a Compose overlay; token signs a development JWT; serve publishes the keys on loopback for `pso dev`. Never for production (refused with PSO_ENV=production)",
    next: "`pso idp:dev token --scopes <scopes>` and send it as `Authorization: Bearer <token>`",
    run(ctx) {
      const sub = ctx.positionals[0];
      const allowed: Record<string, string[]> = {
        init: ["issuer", "audience", "host", "port", "dir", "dry-run", "force", "json"],
        token: ["sub", "scopes", "roles", "ttl", "audience", "dir", "json"],
        serve: ["port", "dir", "once"],
      };
      if (!sub || !allowed[sub]) throw new CliError(`Unknown idp:dev action "${sub ?? ""}"`, "Use: init | token | serve", 2);
      // the three actions share one usage line; an option of another action is refused instead of ignored
      const foreign = Object.keys(ctx.flags).filter((f) => f !== "help" && !allowed[sub]!.includes(f));
      if (foreign.length) throw new CliError(`${foreign.map((f) => `--${f}`).join(", ")} ${foreign.length > 1 ? "do" : "does"} not apply to \`pso idp:dev ${sub}\``, `Accepted: ${allowed[sub]!.map((f) => `--${f}`).join(", ")}`, 2);
      return sub === "init" ? init(ctx) : sub === "token" ? token(ctx) : serve(ctx);
    },
  },
};
