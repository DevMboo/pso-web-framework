/**
 * The PSO container engine (0.2.0): Docker Engine and Compose run the containers; PSO generates the topology from the declarations
 * (`pso infra:apply`), resolves dependencies, orders operations, verifies health and keeps data safe by default.
 */
const envFlag = (ctx: Ctx): string | undefined => str(ctx.flags["env"]);
const list = (v: string | boolean | undefined): string[] => (typeof v === "string" ? v.split(",").map((x) => x.trim()).filter(Boolean) : []);
export const DOCKERFILE_MARK = "# Generated by `pso docker:build` (PSO 0.2.0). It is yours from now on: PSO never overwrites a Dockerfile that exists.";

function requireDocker(): void {
  const d = dockerReady();
  if (!d.ok) throw new CliError(`Docker is not usable: ${d.reason}`, "Nothing was changed");
}

/** The environment's plan, provisioned first when it is a development environment (local resources are generated automatically). */
export function preparedPlan(ctx: Ctx, root: string, quiet = false): Plan {
  let p = engine(() => plan(root, envFlag(ctx), INFRA_HOOKS));
  if (p.summary.changes > 0 || p.interrupted.length) {
    if (p.kind !== "development") throw new CliError(`the infrastructure of "${p.environment}" is not up to date (${p.summary.changes} change(s))`, `Review and apply it first: pso infra:plan --env ${p.environment}, then pso infra:apply --env ${p.environment} --yes`);
    const r = engine(() => apply(root, { env: p.environment, hooks: INFRA_HOOKS, by: "pso docker" }));
    if (!quiet) ctx.print(`provisioned ${r.applied.filter((a) => a.result === "done").length} infrastructure resource(s) of "${p.environment}" first (pso infra:apply)`);
    p = r.plan;
  }
  const missing = p.resources.filter((r) => r.status === "external-missing");
  if (missing.length) throw new CliError(`"${p.environment}" needs resources that only the operator can supply: ${missing.map((r) => r.id).join(", ")}`, "pso infra:validate --env " + p.environment);
  if (p.summary.drift && !quiet) ctx.print(`warning: ${p.summary.drift} generated file(s) were edited by hand and are used as they are (pso infra:status)`);
  return p;
}

function knownNames(t: Topology): string[] { return startupOrder(t); }
function checkNames(t: Topology, names: string[]): void {
  const known = knownNames(t);
  for (const n of names) if (!known.includes(n)) throw new CliError(`Unknown container "${n}" in "${t.env}"`, `Known: ${known.join(", ")}`);
}

/** Dockerfiles and portable framework packages for every service image; nothing a developer wrote is overwritten. */
function prepareBuildContexts(ctx: Ctx, root: string, t: Topology, only: string[] | undefined): string[] {
  const notes: string[] = [];
  const vendor = ctx.flags["vendor"] === true;
  for (const s of t.services.filter((x) => !only || only.includes(x.name))) {
    const dir = join(root, ...s.decl.path.split("/"));
    if (!existsSync(dir)) throw new CliError(`${s.name}: ${s.decl.path} does not exist`);
    const df = join(dir, "Dockerfile");
    if (s.runtime === "node") {
      const vendored = existsSync(join(dir, ...VENDOR_DIR.split("/")));
      const bound = machineBoundDeps(dir);
      if (bound.length && !vendored && !vendor) throw new CliError(`${s.name}: ${bound.map(([n]) => n).join(", ")} resolve to a path on this machine and cannot be installed inside the image build`, "Re-run with --vendor (the packages are copied into the service as tarballs) or install them from your registry");
      if (vendor && !vendored) { const v = vendorFramework(dir); notes.push(`vendored ${v.packages.length} framework package(s) into ${s.decl.path}/${VENDOR_DIR}`); }
      if (!existsSync(df)) { writeFileSync(df, nodeDockerfile(vendor || vendored).replace("\n", `\n${DOCKERFILE_MARK}\n`)); notes.push(`created ${s.decl.path}/Dockerfile`); }
    } else {
      const vendored = existsSync(join(dir, ...MAVEN_VENDOR_DIR.split("/")));
      if (!vendored && psoVersionOfPom(dir) && !vendor) throw new CliError(`${s.name}: the com.pso artifacts exist only in this machine's Maven repository; the image build cannot resolve them`, "Re-run with --vendor (they are copied into the service), or publish them to a Maven repository the build can reach");
      if (vendor && !vendored) { const v = vendorMaven(dir); notes.push(`vendored com.pso ${v.version} into ${s.decl.path}/${MAVEN_VENDOR_DIR}`); }
      if (!existsSync(df)) { writeFileSync(df, springDockerfile(vendor || vendored).replace("\n", `\n${DOCKERFILE_MARK}\n`)); notes.push(`created ${s.decl.path}/Dockerfile`); }
    }
    if (!existsSync(join(dir, ".dockerignore"))) { writeFileSync(join(dir, ".dockerignore"), dockerignore()); notes.push(`created ${s.decl.path}/.dockerignore`); }
  }
  return notes;
}

const imageExists = (image: string): boolean => spawnSync("docker", ["image", "inspect", image], { stdio: "ignore", windowsHide: true }).status === 0;
const sitePublished = (root: string, t: Topology, fei: string): boolean => existsSync(join(root, ...paths.site(t.env, fei).split("/"), "fei", "current.json"));

function psLines(rows: ReturnType<typeof ps>): string[] {
  if (!rows.length) return ["(no containers)"];
  return rows.map((r) => `${r.service.padEnd(16)} ${r.state.padEnd(9)} ${(r.health || "-").padEnd(10)} ${r.status.padEnd(24)} ${r.ports}`);
}

/**
 * Running containers whose mounted generated configuration (.infra: nginx configuration, certificates, realm, keys) changed after they
 * started. Compose does not see such a change (the definition is the same), and a file replaced atomically keeps its old content inside a
 * running container, so these containers must be re-created to use it (for example the edge after a new FEI added a host to its certificate).
 * The identity provider's realm file is not considered (see below).
 */
export function staleContainers(root: string, c: ComposeTarget, only: string[]): Array<{ service: string; changed: string[] }> {
  const infra = join(root, ".infra");
  const newest = (p: string): number => {
    const st = statSync(p);
    if (!st.isDirectory()) return st.mtimeMs;
    let m = st.mtimeMs;
    for (const f of readdirSync(p)) { try { m = Math.max(m, statSync(join(p, f)).mtimeMs); } catch { /* removed meanwhile */ } }
    return m;
  };
  const out: Array<{ service: string; changed: string[] }> = [];
  for (const r of ps(c).filter((x) => x.state === "running" && only.includes(x.service))) {
    const i = spawnSync("docker", ["inspect", "-f", "{{.State.StartedAt}}|{{json .Mounts}}", r.name], { encoding: "utf8", timeout: 30_000 });
    if (i.status !== 0) continue;
    const bar = i.stdout.indexOf("|");
    const started = Date.parse(i.stdout.slice(0, bar).trim());
    let mounts: Array<{ Type: string; Source: string }> = [];
    try { mounts = JSON.parse(i.stdout.slice(bar + 1)); } catch { continue; }
    const changed: string[] = [];
    for (const m of mounts) {
      if (m.Type !== "bind") continue;
      const parts = m.Source.split(/[\\/]/), k = parts.lastIndexOf(".infra");
      if (k < 0) continue;
      const local = join(infra, ...parts.slice(k + 1));
      // the realm file is imported only when the realm does not exist; later changes reach the running identity provider through its
      // administration API (infra:identity), so a changed realm file never re-creates Keycloak
      if (parts[k + 1] === "identity" && parts[parts.length - 1] === "realm.json") continue;
      if (!local.startsWith(infra) || !existsSync(local)) continue;
      if (newest(local) > started + 1000) changed.push(parts.slice(k + 1).join("/"));
    }
    if (changed.length && Number.isFinite(started)) out.push({ service: r.service, changed });
  }
  return out;
}

async function up(ctx: Ctx, root: string, p: Plan, services: string[], o: { build: boolean; noDeps: boolean }): Promise<number> {
  const t = p.topology;
  const c = composeTarget(root, t);
  const targets = services.length ? (o.noDeps ? services : dependenciesOf(t, services)) : startupOrder(t);
  const toBuild = t.services.filter((s) => targets.includes(s.name) && (o.build || !imageExists(`${t.project}-${s.name}:${t.env}`))).map((s) => s.name);
  if (toBuild.length) {
    for (const n of prepareBuildContexts(ctx, root, t, toBuild)) ctx.print(n);
    ctx.print(`building ${toBuild.join(", ")} ...`);
    const b = await compose(c, ["build", ...toBuild], { onLine: (l) => ctx.print(`  ${redact(l)}`) });
    if (b !== 0) throw new CliError(`the image build failed (exit ${b})`, "The build output is above; nothing was started");
  }
  for (const f of t.frontends) if (targets.includes(f.name) && !sitePublished(root, t, f.name)) ctx.print(`note: ${f.name} has no published release in ${paths.site(t.env, f.name)} yet: it answers 404 until \`pso frontend:build ${f.name}\` and \`pso frontend:publish ${f.name} --env ${t.env}\``);
  const conflicts = await portConflicts(c, t, "stack", targets);
  if (conflicts.length) throw new CliError(`host port(s) already in use: ${conflicts.map((x) => `${x.port} (published by ${x.container})`).join(", ")}`, `Another process listens there (a local \`pso dev\`, another stack, another application). Stop it, or change the port: ${conflicts.some((x) => x.container === "edge") ? `environments.${t.env}.httpsPort in pso.infra.json` : `the service port in pso.workspace.json, or set environments.${t.env}.publishServices to false`}. Nothing was started`);
  ctx.print(`starting ${targets.length} container(s) of "${t.env}" in dependency order: ${targets.join(" -> ")}`);
  const timeout = Number(str(ctx.flags["timeout"]) ?? 300);
  if (!Number.isInteger(timeout) || timeout < 10) throw new CliError("--timeout must be a whole number of seconds (at least 10)");
  const stale = staleContainers(root, c, targets);
  let code = await compose(c, ["up", "-d", "--wait", "--wait-timeout", String(timeout), ...(o.noDeps ? ["--no-deps"] : []), ...(services.length ? targets : [])], { onLine: (l) => ctx.print(`  ${redact(l)}`) });
  if (code === 0 && stale.length) {
    for (const x of stale) ctx.print(`re-creating ${x.service}: its configuration changed after it started (${x.changed.join(", ")})`);
    code = await compose(c, ["up", "-d", "--no-deps", "--force-recreate", "--wait", "--wait-timeout", String(timeout), ...stale.map((x) => x.service)], { onLine: (l) => ctx.print(`  ${redact(l)}`) });
  }
  const rows = ps(c);
  emit(ctx, { environment: t.env, started: code === 0, containers: rows, urls: t.frontends.map((f) => f.url), api: t.api.origin }, [...psLines(rows), "", ...(code === 0 ? [`ready: ${t.frontends.map((f) => f.url).join("  ")}  api ${t.api.origin}`] : [`not every container became healthy (exit ${code}): pso docker:logs <name> --env ${t.env}`])].join("\n"));
  return code === 0 ? 0 : 1;
}

