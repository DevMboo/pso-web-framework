import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { CliError } from "./fsx.ts";
import { emit, requireWorkspace, type Command } from "./commands.ts";
import { orchestratorComponentDir, orchestratorModulesDir } from "./project-structure.ts";

/**
 * `pso types`: the names an orchestrator may use, as TypeScript types.
 *
 * A route names an upstream service and a guard with strings (`metadata: { service: "customers" }`, `security: { guard: "jwt" }`).
 * They are checked by `pso validate` and at start-up, and stay that way. This command adds the compiler to those two checks: it
 * writes src/pso-types.d.ts, which declares the services registered in pso.workspace.json and the guards present in the project.
 * From then on `Upstream.forward`, `UpstreamClient` and ROUTES.pso.ts accept only those names, in the editor and in `tsc`.
 *
 * It is optional and additive: without the file every string is accepted, exactly as before. The file is generated, never edited by
 * hand; run the command again after `pso create service`, `pso services:register` or `pso make:guard` (`--check` tells a pipeline
 * whether it is up to date).
 */
export const TYPES_FILE = "src/pso-types.d.ts";

const guardNames = (orchDir: string): string[] => {
  const names = new Set<string>(["jwt"]); // the framework guard exists in every orchestrator
  const read = (dir: string): void => { if (existsSync(dir)) for (const f of readdirSync(dir)) if (f.endsWith(".guard.ts")) names.add(f.slice(0, -".guard.ts".length)); };
  read(orchestratorComponentDir(orchDir, "guards"));
  const routes = orchestratorModulesDir(orchDir);
  if (existsSync(routes)) for (const mod of readdirSync(routes)) read(join(routes, mod, "guards"));
  return [...names].sort();
};

export function typesSource(services: readonly string[], guards: readonly string[]): string {
  const members = (names: readonly string[]): string => (names.length ? names.map((n) => `    ${JSON.stringify(n)}: true;`).join("\n") : "    // (none)");
  return `// Generated by \`pso types\` from pso.workspace.json and the guards of this project. Do not edit: run the command again.
// It makes the compiler check the service and guard names used in ROUTES.pso.ts, Upstream.forward and UpstreamClient.
import "@pso/http";

declare module "@pso/http" {
  /** the upstream services registered in pso.workspace.json */
  interface PsoServices {
${members(services)}
  }
  /** the guards a route may name: "jwt" (the framework guard) and the *.guard.ts files of this project */
  interface PsoGuards {
${members(guards)}
  }
}
`;
}

export const TYPES_COMMANDS: Record<string, Command> = {
  "types": {
    usage: "pso types [--check] [--dry-run] [--json]",
    summary: "Write src/pso-types.d.ts in the orchestrator: the registered service names and the guard names as TypeScript types, so the compiler checks them wherever they are named (--check: exit 1 when the file is missing or out of date)",
    next: "`npm run typecheck` in the orchestrator; run `pso types` again after adding a service or a guard",
    run(ctx) {
      const { root, config } = requireWorkspace(ctx);
      const orch = config.services.find((s) => s.role === "orchestrator");
      if (!orch) throw new CliError("The workspace has no orchestrator", "Run `pso create orchestrator <name>` first");
      const orchDir = join(root, ...orch.path.split("/"));
      const services = config.services.filter((s) => s.role !== "orchestrator").map((s) => s.name).sort();
      const guards = guardNames(orchDir);
      const text = typesSource(services, guards);
      const file = join(orchDir, ...TYPES_FILE.split("/"));
      const current = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n/g, "\n") : undefined;
      const upToDate = current === text;
      const rel = `${orch.path}/${TYPES_FILE}`;
      if (ctx.flags["check"] === true) {
        emit(ctx, { file: rel, upToDate, services, guards }, upToDate ? `${rel} is up to date (${services.length} service(s), ${guards.length} guard(s))` : `${rel} is ${current === undefined ? "missing" : "out of date"}: run \`pso types\``);
        return upToDate ? 0 : 1;
      }
      const dry = ctx.flags["dry-run"] === true;
      const action = upToDate ? "unchanged" : current === undefined ? "created" : "updated";
      if (!dry && !upToDate) { mkdirSync(dirname(file), { recursive: true }); writeFileSync(file, text); }
      emit(ctx, { dryRun: dry, file: rel, action, services, guards }, `${dry ? "[dry-run] " : ""}${action.padEnd(10)} ${rel}\nservices: ${services.join(", ") || "(none)"}\nguards:   ${guards.join(", ")}`);
      return 0;
    },
  },
};
