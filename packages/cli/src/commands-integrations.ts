import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { CliError } from "./fsx.ts";
import { str } from "./args.ts";
import { emit, requireWorkspace, type Command, type Ctx } from "./commands.ts";
import { CONTRACTS_MARKER, extractContracts, renderContracts } from "./integrations/contracts.ts";
import { formatReport, install, type IntegrationAdapter } from "./integrations/core.ts";
import { ADAPTERS } from "./integrations/index.ts";
import { isOrchestratorDir } from "./project-structure.ts";

/**
 * `pso install:<framework> <integration>`: one command per registered framework adapter (today: react). Adding a framework is adding an
 * adapter to integrations/index.ts; this file does not change.
 */
function installCommand(adapter: IntegrationAdapter): Command {
  return {
    usage: `pso install:${adapter.framework} <${adapter.integrations.join("|")}> [--dir <folder>] [--contracts <orchestrator>] [--dry-run] [--skip-install] [--json]`,
    summary: `Install an official PSO integration into an existing ${adapter.framework} application: detects the project and its package manager, installs the packages, writes small application-owned files, never overwrites yours, then type-checks the result`,
    run(ctx: Ctx) {
      const integration = ctx.positionals[0];
      if (!integration) throw new CliError("Name the integration", `pso install:${adapter.framework} ${adapter.integrations[0]}`);
      const report = install(adapter, integration, ctx.cwd, ctx.flags);
      emit(ctx, report, formatReport(report));
      return report.problems.length ? 1 : 0;
    },
  };
}

export const INTEGRATION_COMMANDS: Record<string, Command> = {
  ...Object.fromEntries(Object.values(ADAPTERS).map((a) => [`install:${a.framework}`, installCommand(a)])),

  "channels:contracts": {
    usage: "pso channels:contracts [--from <orchestrator folder> | --service <orchestrator>] [--out src/integrations/pso/types.ts] [--json]",
    summary: "Generate the client-safe TypeScript contracts of the registered channels (names, parameters, event and command payloads) for a front end; internal channels, publishers, scopes and policies are never included",
    run(ctx) {
      let from = str(ctx.flags["from"]);
      if (from) from = resolve(ctx.cwd, from);
      else {
        const { root, config } = requireWorkspace(ctx);
        const name = str(ctx.flags["service"]);
        const orch = config.services.find((s) => s.runtime === "node" && s.role === "orchestrator" && (!name || s.name === name));
        if (!orch) throw new CliError("No orchestrator found", "Pass --from <path to the orchestrator> or --service <name>");
        from = join(root, ...orch.path.split("/"));
      }
      if (!isOrchestratorDir(from)) throw new CliError(`${from} is not a PSO orchestrator (no src/modules, src/.app or src/routes)`);
      const out = resolve(ctx.cwd, str(ctx.flags["out"]) ?? "src/integrations/pso/types.ts");
      const contracts = extractContracts(from);
      const rendered = renderContracts(contracts);
      const text = rendered.text;
      if (existsSync(out) && !readFileSync(out, "utf8").split("\n").slice(0, 3).join("\n").includes(CONTRACTS_MARKER)) throw new CliError(`${out} exists and was not generated by PSO: it was not changed`, "Choose another file with --out");
      const changed = !existsSync(out) || readFileSync(out, "utf8") !== text;
      if (changed) { mkdirSync(dirname(out), { recursive: true }); writeFileSync(out, text); }
      emit(ctx, { out, channels: contracts.channels.map((c) => c.pattern), changed, warnings: rendered.warnings }, [`${changed ? "wrote" : "unchanged"} ${out}`, ...contracts.channels.map((c) => `  ${c.pattern}  events: ${Object.keys(c.events).join(", ") || "-"}  commands: ${Object.keys(c.commands).join(", ") || "-"}`), ...rendered.warnings.map((w) => `warning: ${w}`)].join("\n"));
      return 0;
    },
  },
};
