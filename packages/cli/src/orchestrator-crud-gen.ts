import { names, sortFields, type FieldSpec, type ResourceSpec } from "./crud-spec.ts";
import { MODULAR_PATHS, type ModulePaths } from "./http-gen.ts";

/**
 * The modular orchestrator module of one CRUD resource (official structure, 0.2.0):
 *
 *   modules/<plural>/MODULE.pso.ts                        the module: controllers and providers it owns
 *   modules/<plural>/routes/ROUTES.pso.ts                 the endpoints it exposes and their access policy
 *   modules/<plural>/controllers/<r>.controller.ts        HTTP: validated input, delegation, status codes
 *   modules/<plural>/services/<r>.service.ts              orchestration of the operation (no persistence, no duplicated business rules)
 *   modules/<plural>/providers/<r>.provider.ts            the call to the microservice: PSO discovery, TLS/mTLS, caller identity
 *   modules/<plural>/contracts/<r>.contract.ts            the microservice API this module depends on (types + the service it is bound to)
 *   modules/<plural>/dto/request/{create,update}-<r>.dto.ts   validated request bodies
 *   modules/<plural>/dto/response/<r>.dto.ts               response contracts (published to typed frontends)
 *   modules/<plural>/mappers/<r>.mapper.ts                microservice record -> public response
 */
export interface OrchestratorCrudOptions {
  /** the workspace service that serves this resource (the binding: ROUTES metadata.services and the contract constant) */
  service: string;
  /** the module directory name (the plural by default) */
  module: string;
  reference: boolean;
  paths?: ModulePaths;
}

const UUID_RE = "/^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$/";
const decimalRe = (f: FieldSpec): string => `/^${f.min !== undefined && Number(f.min) < 0 ? "-?" : ""}\\d{1,${(f.precision ?? 12) - (f.scale ?? 2)}}(\\.\\d{1,${f.scale ?? 2}})?$/`;
const tsType = (f: FieldSpec): string => ({ string: "string", text: "string", integer: "number", long: "number", decimal: "string", boolean: "boolean" })[f.type];

function dtoField(f: FieldSpec, update: boolean, imp: Set<string>): string {
  const d: string[] = [];
  const required = f.required || (update && f.type === "boolean");
  const add = (x: string, name = x.replace(/\(.*$/, "")) => { imp.add(name); d.push(`@${x}`); };
  add(required ? "Required()" : "Optional()");
  if (f.type === "string" || f.type === "text") {
    add("StringField()");
    if (f.minLength) add(`MinLength(${f.minLength})`);
    if (f.maxLength) add(`MaxLength(${f.maxLength})`);
    if (f.pattern) add(`Pattern(/^${f.pattern}$/)`);
    if (f.patternMessage) add(`Message(${JSON.stringify(f.patternMessage)})`);
  } else if (f.type === "decimal") {
    add("StringField()"); add(`Pattern(${decimalRe(f)})`);
    add(`Message(${JSON.stringify(`must be a decimal number with at most ${(f.precision ?? 12) - (f.scale ?? 2)} integer and ${f.scale ?? 2} fraction digits, as a string (for example "12.50")`)})`);
  } else if (f.type === "integer" || f.type === "long") {
    add("IntegerField()");
    if (f.min !== undefined) add(`Min(${f.min})`);
    if (f.max !== undefined) add(`Max(${f.max})`);
  } else add("BooleanField()");
  return `  ${d.join(" ")}\n  ${f.name}${required ? "!" : "?"}: ${tsType(f)};`;
}

export function orchestratorCrudFiles(r: ResourceSpec, o: OrchestratorCrudOptions): Record<string, string> {
  const n = names(r), P = o.paths ?? MODULAR_PATHS, mod = o.module, R = n.Resource, res = n.resource;
  const ex = o.reference ? `\n *\n * Reference example generated by PSO: see docs/reference-crud.md to remove it or to generate another resource the same way.` : "";
  const files: Record<string, string> = {};
  const f = {
    module: P.module(mod), routes: P.routes(mod), controller: P.controller(mod, n.kebab), service: P.service(mod, n.kebab), provider: P.provider(mod, n.kebab),
    contract: P.contract(mod, n.kebab), mapper: P.mapper(mod, n.kebab), create: P.dto(mod, `create-${n.kebab}`), update: P.dto(mod, `update-${n.kebab}`),
    response: P.dto(mod, n.kebab, "response"), page: P.dto(mod, `${n.kebab}-page`, "response"),
  };
  const imp = (from: string, to: string) => P.importOf(from, to);
  const filters = r.fields.filter((x) => x.filter);
  const sorts = sortFields(r);
  const SERVICE = `${n.kebab.replace(/-/g, "_").toUpperCase()}_SERVICE`;
  // the resource path on the microservice, relative to its prefix (the client applies the prefix once)
  const svcPath = (suffix = "") => JSON.stringify(`${n.path}${suffix}`);

  // ---------------------------------------------------------------- contract (the microservice API) + binding
  files[f.contract] = `/**
 * The API of the microservice this module depends on, as it answers (Spring: ${R}Controller, ${R}Response, PageResponse).
 * The orchestrator never persists ${n.table} itself and does not repeat the service's business rules: it validates, authorizes,
 * calls this API and maps the answer.
 *
 * ${SERVICE} is the binding of this module: the workspace service that serves the resource. ROUTES.pso.ts declares the same name
 * (metadata.services), which is what allows the calls at run time. Rebind both with \`pso crud:bind ${mod} --to <service>\`.${ex}
 */
export const ${SERVICE} = ${JSON.stringify(o.service)};

/** a ${res} as the microservice returns it (decimal amounts are strings: their exact value is kept) */
export interface ${R}Record {
  id: string;
${r.fields.map((x) => `  ${x.name}: ${tsType(x)}${x.required || x.type === "boolean" ? "" : " | null"};`).join("\n")}
  createdAt: string;
  updatedAt: string;
}

/** one page of a list (the stable contract of every PSO list endpoint) */
export interface ${R}PageRecord {
  items: ${R}Record[];
  page: number;
  size: number;
  totalItems: number;
  totalPages: number;
}

/** what the microservice accepts on create (POST) and on full replacement (PUT) */
export interface ${R}Write {
${r.fields.map((x) => `  ${x.name}${x.required ? "" : "?"}: ${tsType(x)};`).join("\n")}
}

/** filters, paging and sorting of the list, passed to the microservice as query parameters */
export interface ${R}Query {
${filters.map((x) => `  ${x.name}?: ${tsType(x)};`).join("\n")}
  page: number;
  size: number;
  sort?: string;
}
`;

  // ---------------------------------------------------------------- request DTOs
  for (const kind of ["create", "update"] as const) {
    const ii = new Set<string>(["Dto"]);
    const body = r.fields.map((x) => dtoField(x, kind === "update", ii)).join("\n\n");
    const cls = `${kind === "create" ? "Create" : "Update"}${R}Dto`;
    files[kind === "create" ? f.create : f.update] = `import { ${[...ii].sort().join(", ")} } from "@pso/http";

/**
 * ${kind === "create" ? `Body of POST ${n.path}` : `Body of PUT ${n.path}/:id: a full replacement, every field is given`}. Validated by PSO before the controller runs: a
 * violation is a 400 validation_failed problem listing each field, unknown properties are rejected. The microservice validates
 * again (it never trusts its callers), so both layers agree on these rules.
 */
@Dto()
export class ${cls} {
${body}
}
`;
  }

  // ---------------------------------------------------------------- response DTOs (published contract)
  {
    const ii = new Set(["Dto", "Required", "StringField", "Uuid", "IsoDate"]);
    const fields = r.fields.map((x) => {
      const dec = x.type === "boolean" ? "BooleanField" : x.type === "integer" || x.type === "long" ? "IntegerField" : "StringField";
      ii.add(dec); if (!(x.required || x.type === "boolean")) ii.add("Nullable");
      return `  @Required() @${dec}()${x.required || x.type === "boolean" ? "" : " @Nullable()"}\n  ${x.name}!: ${tsType(x)}${x.required || x.type === "boolean" ? "" : " | null"};`;
    }).join("\n\n");
    files[f.response] = `import { ${[...ii].sort().join(", ")} } from "@pso/http";

/** A ${res} as this API returns it (ROUTES.pso.ts publishes it as the response contract for typed frontends). */
@Dto()
export class ${R}Response {
  @Required() @Uuid()
  id!: string;

${fields}

  @Required() @IsoDate()
  createdAt!: string;

  @Required() @IsoDate()
  updatedAt!: string;
}
`;
    files[f.page] = `import { ArrayOf, Dto, IntegerField, Required } from "@pso/http";
import { ${R}Response } from "${imp(f.page, f.response)}";

/** One page of ${n.table}: the items and where the page is in the whole result. */
@Dto()
export class ${R}PageResponse {
  @Required() @ArrayOf(${R}Response)
  items!: ${R}Response[];

  @Required() @IntegerField()
  page!: number;

  @Required() @IntegerField()
  size!: number;

  @Required() @IntegerField()
  totalItems!: number;

  @Required() @IntegerField()
  totalPages!: number;
}
`;
  }

  // ---------------------------------------------------------------- mapper
  files[f.mapper] = `import type { ${R}PageRecord, ${R}Record } from "${imp(f.mapper, f.contract)}";
import type { ${R}PageResponse } from "${imp(f.mapper, f.page)}";
import type { ${R}Response } from "${imp(f.mapper, f.response)}";

/**
 * Microservice record -> public response. Only the fields of the public contract are copied: anything else the service might add
 * later (an internal flag, a version) does not leak through the orchestrator by accident.
 */
export function to${R}Response(record: ${R}Record): ${R}Response {
  return {
    id: record.id,
${r.fields.map((x) => `    ${x.name}: record.${x.name}${x.required || x.type === "boolean" ? "" : " ?? null"},`).join("\n")}
    createdAt: record.createdAt,
    updatedAt: record.updatedAt,
  };
}

export function to${R}Page(page: ${R}PageRecord): ${R}PageResponse {
  return { items: page.items.map(to${R}Response), page: page.page, size: page.size, totalItems: page.totalItems, totalPages: page.totalPages };
}
`;

  // ---------------------------------------------------------------- provider (the microservice call)
  files[f.provider] = `import { HttpError, Injectable, UpstreamCallError, UpstreamClient } from "@pso/http";
import { ${SERVICE}, type ${R}PageRecord, type ${R}Query, type ${R}Record, type ${R}Write } from "${imp(f.provider, f.contract)}";

/**
 * Talks to the microservice that owns ${n.table}. UpstreamClient resolves "${o.service}" through PSO service discovery (the workspace
 * declaration, no URL here), applies its endpoint prefix, uses its TLS / mutual TLS material, carries the correlation id and the
 * trace, and sends the caller's token ("caller" credentials) so the service authorizes the same user again.
 *
 * Downstream outcomes the client can act on are translated into this API's problems (404, 409, 400 with the service's safe detail);
 * everything else (timeout, unavailable, TLS) is left to the framework, which answers a stable 502/503/504 problem.
 */
@Injectable()
export class ${R}Provider {
  constructor(private readonly client: UpstreamClient) {}

  list(query: ${R}Query): Promise<${R}PageRecord> {
    return translate(this.client.get<${R}PageRecord>(${SERVICE}, ${svcPath()}, { query: { ...query }, credentials: "caller" }));
  }

  find(id: string): Promise<${R}Record> {
    return translate(this.client.get<${R}Record>(${SERVICE}, ${svcPath("/:id")}, { params: { id }, credentials: "caller" }));
  }

  create(body: ${R}Write): Promise<${R}Record> {
    return translate(this.client.post<${R}Record>(${SERVICE}, ${svcPath()}, body, { credentials: "caller" }));
  }

  update(id: string, body: ${R}Write): Promise<${R}Record> {
    return translate(this.client.put<${R}Record>(${SERVICE}, ${svcPath("/:id")}, body, { params: { id }, credentials: "caller" }));
  }

  async delete(id: string): Promise<void> {
    await translate(this.client.delete<unknown>(${SERVICE}, ${svcPath("/:id")}, { params: { id }, credentials: "caller" }));
  }
}

async function translate<T>(call: Promise<T>): Promise<T> {
  try {
    return await call;
  } catch (e) {
    if (e instanceof UpstreamCallError && e.kind === "status") {
      const detail = e.problem?.detail;
      if (e.status === 404) throw new HttpError(404, "not_found", detail ? { detail } : {});
      if (e.status === 409) throw new HttpError(409, "conflict", detail ? { detail } : {});
      if (e.status === 400) throw new HttpError(400, "bad_request", detail ? { detail } : {});
    }
    throw e;
  }
}
`;

  // ---------------------------------------------------------------- service
  files[f.service] = `import { Injectable } from "@pso/http";
import type { ${R}Query, ${R}Write } from "${imp(f.service, f.contract)}";
import type { Create${R}Dto } from "${imp(f.service, f.create)}";
import type { Update${R}Dto } from "${imp(f.service, f.update)}";
import type { ${R}PageResponse } from "${imp(f.service, f.page)}";
import type { ${R}Response } from "${imp(f.service, f.response)}";
import { to${R}Page, to${R}Response } from "${imp(f.service, f.mapper)}";
import { ${R}Provider } from "${imp(f.service, f.provider)}";

/**
 * The operations of this module. It coordinates (call the provider, map the answer); it does not persist anything and does not
 * repeat rules the microservice owns (uniqueness, existence): those answers come back as problems and pass through.
 */
@Injectable()
export class ${R}Service {
  constructor(private readonly provider: ${R}Provider) {}

  async list(query: ${R}Query): Promise<${R}PageResponse> {
    return to${R}Page(await this.provider.list(query));
  }

  async find(id: string): Promise<${R}Response> {
    return to${R}Response(await this.provider.find(id));
  }

  async create(body: Create${R}Dto): Promise<${R}Response> {
    return to${R}Response(await this.provider.create(toWrite(body)));
  }

  async update(id: string, body: Update${R}Dto): Promise<${R}Response> {
    return to${R}Response(await this.provider.update(id, toWrite(body)));
  }

  async remove(id: string): Promise<void> {
    await this.provider.delete(id);
  }
}

/** the validated body, field by field (a validated DTO has no other properties; copying keeps the contract explicit) */
function toWrite(body: Create${R}Dto | Update${R}Dto): ${R}Write {
  return { ${r.fields.map((x) => `${x.name}: body.${x.name}`).join(", ")} };
}
`;

  // ---------------------------------------------------------------- controller
  const sortRe = `/^(${sorts.join("|")})(,(asc|desc))?$/`;
  const queryArgs = filters.map((x) => `@Query("${x.name}", { type: "${x.type === "boolean" ? "boolean" : "string"}"${x.type !== "boolean" && x.maxLength ? `, maxLength: ${x.maxLength}` : ""} }) ${x.name}: ${x.type === "boolean" ? "boolean" : "string"} | undefined`);
  files[f.controller] = `import { Body, Controller, Delete, Get, Param, Post, Put, Query, RestController, created, noContent } from "@pso/http";
import type { ${R}Query } from "${imp(f.controller, f.contract)}";
import { Create${R}Dto } from "${imp(f.controller, f.create)}";
import { Update${R}Dto } from "${imp(f.controller, f.update)}";
import { ${R}Service } from "${imp(f.controller, f.service)}";

const ID = { type: "string", pattern: ${UUID_RE} } as const;
const SORT = ${sortRe};
const MAX_PAGE_SIZE = ${r.maxPageSize};

/**
 * HTTP endpoints of ${n.table}. An action runs only if ROUTES.pso.ts declares it; its authentication and scopes are checked there
 * before this code runs, and every parameter below is validated (a violation is a 400 problem, the action is not called).${ex}
 */
@Controller()
@RestController(${JSON.stringify(n.path)})
export class ${R}Controller {
  constructor(private readonly ${n.resources}: ${R}Service) {}

  /** public example: what the list accepts. It answers from the orchestrator alone and never reaches the microservice. */
  @Get("/options")
  options() {
    return { sort: [${sorts.map((s) => JSON.stringify(s)).join(", ")}], directions: ["asc", "desc"], filters: [${filters.map((x) => JSON.stringify(x.name)).join(", ")}], maxPageSize: MAX_PAGE_SIZE, defaultPageSize: ${r.defaultPageSize} };
  }

  @Get("/")
  async list(
${queryArgs.map((q) => `    ${q},`).join("\n")}
    @Query("page", { type: "integer", min: 0, default: 0 }) page: number,
    @Query("size", { type: "integer", min: 1, max: MAX_PAGE_SIZE, default: ${r.defaultPageSize} }) size: number,
    @Query("sort", { type: "string", pattern: SORT }) sort: string | undefined,
  ) {
    const query: ${R}Query = { page, size };
${[...filters.map((x) => x.name), "sort"].map((k) => `    if (${k} !== undefined) query.${k} = ${k};`).join("\n")}
    return this.${n.resources}.list(query);
  }

  @Get("/:id")
  async find(@Param("id", ID) id: string) {
    return this.${n.resources}.find(id);
  }

  @Post("/")
  async create(@Body(Create${R}Dto) body: Create${R}Dto) {
    const ${res} = await this.${n.resources}.create(body);
    return created(${res}, \`${n.path}/\${${res}.id}\`);
  }

  @Put("/:id")
  async update(@Param("id", ID) id: string, @Body(Update${R}Dto) body: Update${R}Dto) {
    return this.${n.resources}.update(id, body);
  }

  @Delete("/:id")
  async remove(@Param("id", ID) id: string) {
    await this.${n.resources}.remove(id);
    return noContent();
  }
}
`;

  // ---------------------------------------------------------------- routes + module
  const read = `{ guard: "jwt", scopes: ["${n.readScope}"] }`, write = `{ guard: "jwt", scopes: ["${n.writeScope}"] }`;
  const meta = `{ services: [${JSON.stringify(o.service)}] }`;
  const route = (method: string, path: string, action: string, security: string, extra = "") => `    { method: "${method}", path: "${path}", controller: ${R}Controller, action: "${action}", security: ${security}${security.includes("public") ? "" : `, metadata: ${meta}`}${extra} },`;
  files[f.routes] = `import { defineRoutes } from "@pso/http";
import { ${R}Controller } from "${imp(f.routes, f.controller)}";

// The endpoints of the ${mod} module and their access policy. Nothing else of ${R}Controller is reachable.
//   ${n.readScope}  / ${n.writeScope}   scopes of the JWT (the identity provider's roles); the microservice checks them again
//   metadata.services      the services an action may call (UpstreamClient refuses any other), here "${o.service}"
// A literal path wins over a parameter: the public ${n.path}/options is never taken for ${n.path}/:id.
export default defineRoutes({
  routes: [
${route("GET", `${n.path}/options`, "options", "{ public: true }")}
${route("GET", n.path, "list", read, `, responses: { 200: "${R}PageResponse", 400: "problem", 401: "problem", 403: "problem" }`)}
${route("GET", `${n.path}/:id`, "find", read, `, responses: { 200: "${R}Response", 404: "problem" }`)}
${route("POST", n.path, "create", write, `, responses: { 201: "${R}Response", 400: "problem", 409: "problem" }`)}
${route("PUT", `${n.path}/:id`, "update", write, `, responses: { 200: "${R}Response", 400: "problem", 404: "problem", 409: "problem" }`)}
${route("DELETE", `${n.path}/:id`, "remove", write, `, responses: { 204: "void", 404: "problem" }`)}
  ],
});
`;
  files[f.module] = `import { defineModule } from "@pso/core";
import ${n.resources}Routes from "${imp(f.module, f.routes)}";
import { ${R}Controller } from "${imp(f.module, f.controller)}";
import { ${R}Service } from "${imp(f.module, f.service)}";
import { ${R}Provider } from "${imp(f.module, f.provider)}";

// The ${mod} module: what it owns and what it exposes. Discovered from src/modules/${mod}/; registered by this declaration only.
export default defineModule({
  name: "${mod}",
  controllers: [${R}Controller],
  providers: [${R}Service, ${R}Provider],
  routes: ${n.resources}Routes,
  imports: [],
  exports: [],
});
`;
  return files;
}

/** Unit tests of the module's pure parts (the mapper), runnable with `npm test` in the orchestrator. */
export function orchestratorCrudTests(r: ResourceSpec, o: { module: string }): Record<string, string> {
  const n = names(r), R = n.Resource;
  const sampleRec = `{ id: "7b7b0c39-0f3b-4b52-8c6b-1d7b4ce9f001", ${r.fields.map((x) => `${x.name}: ${x.type === "boolean" ? "true" : x.type === "integer" || x.type === "long" ? "1" : JSON.stringify(x.type === "decimal" ? "12.50" : "KB-100")}`).join(", ")}, createdAt: "2026-01-01T00:00:00Z", updatedAt: "2026-01-01T00:00:00Z" }`;
  return {
    [`tests/${o.module}/${n.kebab}.mapper.test.ts`]: `import { test } from "node:test";
import assert from "node:assert/strict";
import { to${R}Page, to${R}Response } from "../../src/modules/${o.module}/mappers/${n.kebab}.mapper";

test("the public response carries exactly the contract fields", () => {
  const record = { ...${sampleRec}, internalFlag: true } as never;
  const out = to${R}Response(record) as unknown as Record<string, unknown>;
  assert.equal(out["internalFlag"], undefined, "fields outside the contract never leak");
  assert.deepEqual(Object.keys(out).sort(), ["createdAt", "id", "updatedAt", ${r.fields.map((x) => JSON.stringify(x.name)).join(", ")}].sort());
});

test("a page keeps its position and maps every item", () => {
  const page = to${R}Page({ items: [${sampleRec}], page: 2, size: 10, totalItems: 21, totalPages: 3 });
  assert.deepEqual([page.items.length, page.page, page.size, page.totalItems, page.totalPages], [1, 2, 10, 21, 3]);
});
`,
  };
}

/**
 * The reference request collection of a CRUD module (docs/api/<plural>.collection.json in the orchestrator), shown read-only by the
 * Studio API Client. Requests go through the orchestrator (target edge:api, the public API) unless they say otherwise; one goes directly
 * to the microservice (target process:<service>), which authorizes it itself. Authentication is a development user chosen in Studio:
 * no token or credential is ever written here.
 */
export function orchestratorCrudCollection(r: ResourceSpec, o: { service: string; servicePrefix: string }): string {
  const n = names(r);
  const body = (i: number, over: Record<string, unknown> = {}) => JSON.stringify(Object.fromEntries(r.fields.map((f) => [f.name, f.name in over ? over[f.name] : f.type === "boolean" ? true : f.type === "integer" || f.type === "long" ? 1 + i : f.type === "decimal" ? (12.5 + i).toFixed(f.scale ?? 2) : f.unique || f.pattern ? `KB-${100 + i}` : `Sample ${f.name} ${i}`])), null, 2);
  const json = (text: string) => ({ kind: "json", text });
  const user = { kind: "dev-user" };
  const firstText = r.fields.find((f) => f.filter === "contains");
  const requests = [
    { name: `${n.Resources}: options (public)`, method: "GET", path: `${n.path}/options`, auth: { kind: "none" }, note: "public: answered by the orchestrator, no token" },
    { name: `${n.Resources}: create`, method: "POST", path: n.path, body: json(body(0)), auth: user, note: `201 + Location; needs ${n.writeScope}; copy the id into {{${n.resource}Id}}` },
    { name: `${n.Resources}: list (page, size, sort)`, method: "GET", path: n.path, query: [["page", "0"], ["size", "20"], ["sort", "createdAt,desc"]], auth: user, note: `needs ${n.readScope}` },
    ...(firstText ? [{ name: `${n.Resources}: filter`, method: "GET", path: n.path, query: [[firstText.name, "sample"], ...(r.fields.some((f) => f.type === "boolean" && f.filter) ? [[r.fields.find((f) => f.type === "boolean" && f.filter)!.name, "true"]] : [])], auth: user, note: "database-level filtering" }] : []),
    { name: `${n.Resources}: find`, method: "GET", path: `${n.path}/{{${n.resource}Id}}`, auth: user },
    { name: `${n.Resources}: update (PUT, full replacement)`, method: "PUT", path: `${n.path}/{{${n.resource}Id}}`, body: json(body(1)), auth: user },
    { name: `${n.Resources}: delete`, method: "DELETE", path: `${n.path}/{{${n.resource}Id}}`, auth: user, note: "204" },
    { name: `${n.Resources}: invalid body (400)`, method: "POST", path: n.path, body: json(JSON.stringify({ [r.fields[0]!.name]: "" })), auth: user, note: "validation_failed with the fields at fault" },
    ...(r.fields.some((f) => f.unique) ? [{ name: `${n.Resources}: duplicate (409)`, method: "POST", path: n.path, body: json(body(0)), auth: user, note: "send it after the create request" }] : []),
    { name: `${n.Resources}: missing (404)`, method: "GET", path: `${n.path}/00000000-0000-0000-0000-000000000000`, auth: user },
    { name: `${n.Resources}: unauthorized (401)`, method: "GET", path: n.path, auth: { kind: "none" }, note: "no token" },
    { name: `${n.Resources}: forbidden (403)`, method: "POST", path: n.path, body: json(body(2)), auth: user, note: `choose a development user WITHOUT ${n.writeScope}` },
    { name: `${n.Resources}: directly to ${o.service} (bypasses the orchestrator)`, method: "GET", path: `${o.servicePrefix}${n.path}`, target: `process:${o.service}`, auth: user, note: `the microservice authorizes the token itself (${n.readScope})` },
  ].map((x) => ({ target: "edge:api", ...x }));
  return JSON.stringify({ name: `${n.Resources} (reference CRUD)`, description: `Requests for the ${n.table} API of ${o.service} through this orchestrator. Generated by PSO; safe to keep in version control: it holds no credential.`, variables: [[`${n.resource}Id`, ""]], requests }, null, 2) + "\n";
}
